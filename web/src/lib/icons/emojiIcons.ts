/** The Hugeicons equivalent of a stored or literal emoji, if there is one. */
export function iconForEmoji(emoji: string | null | undefined): IconSvgElement | undefined {
	if (!emoji) return undefined;
	return EMOJI_ICONS[emoji.replace(/️/g, '').trim()];
}
